#!/bin/bash
# ==============================================================================
# 礼金收聘系统 · 账房云枢 - 一键从 GitHub 同步更新 (Mac/Linux)
# ==============================================================================

DIR="$( cd "$( dirname "${BASH_SOURCE[0]}" )/.." && pwd )"
cd "$DIR"

echo ""
echo "==============================================================="
echo "     🏮 礼金收聘系统 · 账房云枢 - GitHub 云端同步更新 (Mac/Linux)"
echo "==============================================================="
echo ""

echo "正在拉取 GitHub 云端最新代码..."
git pull origin main

if [ $? -eq 0 ]; then
    echo ""
    echo "正在检查依赖完整性..."
    npm install --registry=https://registry.npmmirror.com
    echo ""
    echo "==============================================================="
    echo "       🎉 系统已成功更新至 GitHub 最新版本！                    "
    echo "==============================================================="
    echo ""
else
    echo "[错误] 同步遇到异常，请检查网络或 Git 状态。"
fi
